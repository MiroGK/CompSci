package Aug28;

public class BlockLetters {
    public static void main(String[] args) {
        System.out.println(" ");
        System.out.println(" A");
        System.out.println("A A");
        System.out.println("AAA");
        System.out.println("A A");
        System.out.println("A A");
        System.out.println(" ");
        System.out.print("B");
        System.out.println("B");
        System.out.println("B B");
        System.out.println("BB");
        System.out.println("B B");
        System.out.println("BB");
        System.out.println(" ");
    }
}
